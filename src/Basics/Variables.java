package Basics;

public class Variables {
    public static void main(String[] args) {

        int age = 20;
        double height = 6.0;
        String name = "Harsha";
        boolean student = true;

        System.out.println("Name: " + name);
        System.out.println("Age: " + age);
        System.out.println("Height: " + height);
        System.out.println("Student: " + student);
    }
}